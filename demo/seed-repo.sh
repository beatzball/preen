# Design notes

Three rules this service follows.

1. **One route.** Everything is a slug lookup.
2. **No state.** Restarting loses nothing.
3. **JSON only.** No HTML, no templates.

- [x] slugify handles punctuation
- [x] truncate adds an ellipsis
- [ ] rate limiting

## Why Python for the helpers

`re.sub` is short and the rules fit on one line:

```python
re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
```
