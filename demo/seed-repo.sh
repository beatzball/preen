#!/usr/bin/env bash
# Build a small throwaway git repo with real changes, for the demo recordings.
#
#   ./demo/seed-repo.sh /tmp/preen-demo-repo
#
# It makes three things, all under DIR:
#   * a dirty working tree            -> preen diff, git diff | preen
#   * three git worktrees in .worktrees/ -> preen worktrees
#   * a bare sandbox in .pr/          -> preen pr (origin points at a public repo)
# .worktrees/ and .pr/ are git-ignored, so they never show up in preen diff.
set -euo pipefail
D="${1:?usage: seed-repo.sh DIR}"
rm -rf "$D"; mkdir -p "$D/src"; cd "$D"
D="$PWD"                                   # absolute, for git worktree add

# every commit below, with no dependency on the caller's git identity
g() { git -c user.name=demo -c user.email=demo@example.com "$@"; }

git init -q -b main .
cat > .gitignore <<'A'
.worktrees/
.pr/
A
cat > src/server.js <<'A'
const http = require("http");

function handler(req, res) {
  res.writeHead(200, { "Content-Type": "text/plain" });
  res.end("hello\n");
}

http.createServer(handler).listen(3000);
A
cat > src/util.py <<'A'
def slugify(text):
    return text.lower().replace(" ", "-")

def truncate(text, n):
    return text[:n]
