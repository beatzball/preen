const WINDOW_MS = 60_000;
const MAX = 120;
const hits = new Map();

function allow(key, now = Date.now()) {
  const seen = (hits.get(key) || []).filter((t) => now - t < WINDOW_MS);
  seen.push(now);
  hits.set(key, seen);
  return seen.length <= MAX;
}

module.exports = { allow, WINDOW_MS, MAX };
